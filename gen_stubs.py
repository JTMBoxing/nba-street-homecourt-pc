# Regenerates runtime/stubs.cpp: a logging stub for every called import not implemented in runtime/*.cpp
import re,glob
impl=set()
for f in glob.glob('runtime/*.cpp'):
    if f.endswith('stubs.cpp'): continue
    impl|=set(re.findall(r'^IMPORT\((\w+)\)',open(f).read(),re.M))
calls=[l.strip() for l in open('imports_called.txt') if l.strip()]
special={'NetDll_socket':'0xFFFFFFFF','NetDll_accept':'0xFFFFFFFF','NetDll_WSAGetLastError':'10050','NetDll_XNetGetTitleXnAddr':'1','XamContentCreateEx':'0x48F','XamContentGetDeviceState':'0x48F','XamShowDeviceSelectorUI':'0x48F','XamShowSigninUI':'0x48F','XamUserReadProfileSettings':'0x525','XamCreateEnumeratorHandle':'0x12','XamContentCreateEnumerator':'0x12','XamEnumerate':'0x12','XamVoiceCreate':'0x48F'}
out=['// Generated by gen_stubs.py: logging stubs for system functions not implemented yet.','#include "guest.h"','']
miss=[c for c in calls if c not in impl]
out+= [f'IMPORT({c}) {{ Unimplemented("{c}", ctx); RETURN({special.get(c,"0")}); }}' for c in miss]
open('runtime/stubs.cpp','w').write('\n'.join(out)+'\n')
print(f'{len(calls)-len(miss)} implemented, {len(miss)} stubbed')
